"""Evaluate the completeness checker on the real-derived samples against seeded_defects.json.

Run from app/backend:  .venv/Scripts/python.exe -X utf8 tests/eval_samples.py
Writes app/EVAL.md. Exit code 1 if any seeded defect is missed or a good sample raises a Section C false alarm.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))

from fastapi.testclient import TestClient  # noqa: E402
from main import app  # noqa: E402

SAMPLES = os.path.join(HERE, "..", "..", "data", "samples")
OUT = os.path.join(HERE, "..", "..", "EVAL.md")
client = TestClient(app)
truth = json.load(open(os.path.join(SAMPLES, "seeded_defects.json"), encoding="utf8"))["samples"]

GOOD = ["good_stair_edmonton", "standata_23_bcv_001_wocd", "standata_23_bcv_004_sprinkler_glazing",
        "standata_23_bcv_008r1_exhaust_clearance"]


def item(items, id_):
    return next((i for i in items if i["id"] == id_), None)


def detected(defect, items):
    """Return (bool, evidence) for one seeded defect, using the real completeness items."""
    path, ev = defect["path"], None
    m = re.fullmatch(r"section_d\[(\d+)\]\.responsible_party", path)
    if m:
        it = item(items, f"D.doc.{m.group(1)}")
        return bool(it and "No responsible professional is named" in it["message"]), it
    m = re.fullmatch(r"section_d\[(\d+)\]\.professional_required", path)
    if m:
        it = item(items, f"D.doc.{m.group(1)}")
        return bool(it and "Not marked as needing" in it["message"]), it
    m = re.fullmatch(r"variance\.section_c\[(\d+)\]\.article", path)
    if m:
        it = item(items, f"C.row.{m.group(1)}")
        return bool(it and it["status"] != "complete" and "not verified" in it["message"]), it
    m = re.fullmatch(r"variance\.acceptable_solution\.articles\[(\d+)\]", path)
    if m:
        it = item(items, f"C.article.{m.group(1)}")
        return bool(it and it["status"] == "missing"), it
    simple = {
        "section_d": "D.documents", "professional_flags": "D.professional_named",
        "variance.acceptable_solution.articles": "C.articles",
        "variance.proposed_alternative.summary": "C.alternative",
        "variance.proposed_alternative.mitigations": "C.mitigations",
        "variance.section_c": "C.table",
    }
    if path in simple:
        it = item(items, simple[path])
        return bool(it and it["status"] == "missing"), it
    m = re.fullmatch(r"project\.(\w+)", path)
    if m:
        it = item(items, f"B.{m.group(1)}")
        return bool(it and it["status"] == "missing"), it
    return False, None


def run(name):
    body = json.load(open(os.path.join(SAMPLES, name + ".json"), encoding="utf8"))
    app_id = client.post("/api/applications", json=body).json()["id"]
    c = client.get(f"/api/applications/{app_id}/completeness").json()
    return c


rows, misses, total, hit = [], [], 0, 0
for name, spec in truth.items():
    c = run(name)
    for d in spec["defects"]:
        ok, it = detected(d, c["items"])
        total += 1
        hit += ok
        rows.append((name, d["id"], d["path"], d["kind"], "DETECTED" if ok else "MISSED"))
        if not ok:
            misses.append((name, d["id"], d["path"]))

# false alarms on the real-derived good samples: Section C structure/citation items must be clean
fa_rows, fa = [], 0
for name in GOOD:
    c = run(name)
    bad = [i for i in c["items"] if i["id"].startswith(("C.row.", "C.article.", "C.table", "C.articles", "C.alternative",
                                                        "C.explanation", "C.code_or_standard"))
           and i["status"] != "complete"]
    # 'uncertain' + root-article note is a genuine flag for a person, not a false alarm
    alarms = [i for i in bad if i["status"] == "missing" or "not verified" in i["message"]
              or "not found" in i["message"]]
    flags = [i for i in bad if i not in alarms]
    fa += len(alarms)
    fa_rows.append((name, c["percent"], len(c["items"]),
                    [f"ALARM {i['id']}: {i['message']}" for i in alarms] +
                    [f"flag {i['id']}: {i['message'][:70]}" for i in flags]))

recall = hit / total if total else 0
lines = [
    "# Completeness checker evaluation (real-derived samples)", "",
    "Generated by `app/backend/tests/eval_samples.py`. Ground truth: `app/data/samples/seeded_defects.json`",
    "(defects were made by removing or corrupting fields of records derived from real STANDATA variances and the",
    "Edmonton PAB guide; nothing was invented). This measures administrative completeness only.", "",
    f"**Seeded-defect recall: {hit}/{total} = {recall:.0%}.**  "
    f"**False alarms on Section C of the good samples: {fa}.**", "",
    "| Sample | Defect | Path | Kind | Result |", "|---|---|---|---|---|",
]
lines += [f"| {r[0]} | {r[1]} | `{r[2]}` | {r[3]} | {r[4]} |" for r in rows]
lines += ["", "## Good samples (should not alarm on Section C)", "",
          "| Sample | Completeness % | Items | Section C alarms |", "|---|---|---|---|"]
for n, pct, k, bad in fa_rows:
    lines.append(f"| {n} | {pct}% | {k} | {'none' if not bad else '; '.join(bad)} |")
lines += ["", "Good samples score below 100% on purpose: identity fields, dates, signatures and the consent boxes are left",
          "for humans, and numeric project facts the source documents do not state are blank.", "",
          "## Honest failures and limits", ""]
lines += [f"- MISSED {m[0]} {m[1]} (`{m[2]}`)" for m in misses] or ["- No seeded defect missed."]
lines += ["- `D.doc.*` 'not marked as requiring a registered professional' fires for any unprovided document on a "
          "single-exit-stair topic; some legitimate non-professional documents (for example a maintenance plan) will "
          "be flagged for confirmation, so precision on that check is below 100%.",
          "- The checker cannot judge whether content is adequate or correct, by design."]
open(OUT, "w", encoding="utf8").write("\n".join(lines) + "\n")
print(f"recall {hit}/{total}; section-C false alarms {fa}; wrote {os.path.abspath(OUT)}")
for m in misses:
    print("MISSED", *m)
sys.exit(1 if (misses or fa) else 0)
